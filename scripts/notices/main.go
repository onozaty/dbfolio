// Command notices generates THIRD_PARTY_NOTICES: the licenses of everything
// that the dbfolio binary contains besides its own code.
//
//	go run ./scripts/notices
//
// It lists the Go modules linked into the binary for every release target
// OS, copies their license files from the module cache, adds the Go standard
// library, and appends third_party/graphviz-wasm (the components built into
// graphviz.wasm, which cannot be found from Go modules).
package main

import (
	"bytes"
	"cmp"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"unicode/utf8"
)

// targetOS are the operating systems of the release binaries. Dependencies
// can differ by OS (e.g. mousetrap is Windows only).
var targetOS = []string{"linux", "darwin", "windows"}

// licenseFile matches the license and notice files at the root of a module.
var licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice)(\.(md|txt))?$`)

// extraFiles are license files outside the module root that must be included.
// freetype is dual-licensed (FreeType License or GPLv2); dbfolio uses it under
// the FreeType License, which its LICENSE refers to but does not contain.
var extraFiles = map[string][]string{
	"github.com/golang/freetype": {"licenses/ftl.txt"},
}

const (
	mainPackage     = "./cmd/dbfolio"
	graphvizWASMDir = "third_party/graphviz-wasm"
)

// graphvizWASMFiles are appended in this order after the NOTICE.
var graphvizWASMFiles = []string{
	"graphviz-LICENSE",
	"expat-COPYING",
	"wasi-libc-LICENSE",
	"wasi-libc-LICENSE-MIT",
	"wasi-libc-musl-COPYRIGHT",
	"wasi-libc-cloudlibc-LICENSE",
}

type module struct {
	Path    string
	Version string
	Dir     string
}

func main() {
	out := flag.String("o", "THIRD_PARTY_NOTICES", "output file")
	flag.Parse()
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	modules, err := linkedModules()
	if err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString("THIRD PARTY NOTICES\n\n")
	b.WriteString("The dbfolio binary contains the following third-party software.\n")
	b.WriteString("This file is generated by scripts/notices; do not edit it by hand.\n")

	goroot, err := goEnv("GOROOT")
	if err != nil {
		return err
	}
	if err := writeSection(&b, "Go standard library", []string{filepath.Join(goroot, "LICENSE")}); err != nil {
		return err
	}
	for _, m := range modules {
		files, err := licenseFiles(m)
		if err != nil {
			return err
		}
		if err := writeSection(&b, m.Path+" "+m.Version, files); err != nil {
			return err
		}
	}
	files := []string{filepath.Join(graphvizWASMDir, "NOTICE")}
	for _, f := range graphvizWASMFiles {
		files = append(files, filepath.Join(graphvizWASMDir, f))
	}
	if err := writeSection(&b, "graphviz.wasm", files); err != nil {
		return err
	}
	return os.WriteFile(out, b.Bytes(), 0o644)
}

// linkedModules returns the modules (other than dbfolio) whose packages are
// linked into the binary on any target OS, sorted by path.
func linkedModules() ([]module, error) {
	seen := make(map[string]module)
	for _, goos := range targetOS {
		cmd := exec.Command("go", "list", "-deps", "-json=Module", mainPackage)
		cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH=amd64", "CGO_ENABLED=0")
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		outb, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list (GOOS=%s): %w\n%s", goos, err, stderr.String())
		}
		dec := json.NewDecoder(bytes.NewReader(outb))
		for {
			var pkg struct {
				Module *struct {
					Path    string
					Version string
					Dir     string
					Main    bool
				}
			}
			if err := dec.Decode(&pkg); errors.Is(err, io.EOF) {
				break
			} else if err != nil {
				return nil, err
			}
			// Standard library packages have no module; dbfolio is the main module.
			if pkg.Module == nil || pkg.Module.Main {
				continue
			}
			seen[pkg.Module.Path] = module{pkg.Module.Path, pkg.Module.Version, pkg.Module.Dir}
		}
	}
	modules := make([]module, 0, len(seen))
	for _, m := range seen {
		modules = append(modules, m)
	}
	slices.SortFunc(modules, func(a, b module) int { return cmp.Compare(a.Path, b.Path) })
	return modules, nil
}

func licenseFiles(m module) ([]string, error) {
	entries, err := os.ReadDir(m.Dir)
	if err != nil {
		return nil, err
	}
	var files []string
	for _, e := range entries {
		if !e.IsDir() && licenseFile.MatchString(e.Name()) {
			files = append(files, filepath.Join(m.Dir, e.Name()))
		}
	}
	for _, f := range extraFiles[m.Path] {
		files = append(files, filepath.Join(m.Dir, f))
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no license file found in %s %s", m.Path, m.Version)
	}
	return files, nil
}

func writeSection(b *bytes.Buffer, title string, files []string) error {
	b.WriteString("\n" + strings.Repeat("=", 78) + "\n")
	b.WriteString(title + "\n")
	b.WriteString(strings.Repeat("=", 78) + "\n")
	for _, f := range files {
		text, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		if !utf8.Valid(text) {
			// Old license files are in Latin-1 (e.g. "©" in freetype's ftl.txt).
			text = latin1ToUTF8(text)
		}
		fmt.Fprintf(b, "\n--- %s ---\n\n", filepath.Base(f))
		// Normalize line endings and trailing space so the output is the same everywhere.
		lines := strings.Split(strings.ReplaceAll(string(text), "\r\n", "\n"), "\n")
		for i, l := range lines {
			lines[i] = strings.TrimRight(l, " \t")
		}
		b.WriteString(strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n")
	}
	return nil
}

func latin1ToUTF8(b []byte) []byte {
	runes := make([]rune, len(b))
	for i, c := range b {
		runes[i] = rune(c)
	}
	return []byte(string(runes))
}

func goEnv(key string) (string, error) {
	out, err := exec.Command("go", "env", key).Output()
	if err != nil {
		return "", fmt.Errorf("go env %s: %w", key, err)
	}
	return strings.TrimSpace(string(out)), nil
}
