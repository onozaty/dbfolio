package render

import (
	"fmt"
	"html/template"
	"strings"

	"github.com/onozaty/dbfolio/internal/schema"
)

// page is the data common to all pages.
type page struct {
	// Root is the relative path from the page to the output root ("" or "../"),
	// so that links work when opened via file://.
	Root   string
	Title  string
	DBName string
	// Fill makes the main content fill the window height instead of the page
	// scrolling, so that a large diagram scrolls only inside its own frame.
	Fill bool
	// Current is the menu item of the page (see menu* constants); empty for
	// table pages, which are not menu items.
	Current string
	// Count tells the size of a list page next to its heading (e.g. "34 columns").
	Count string
}

// Menu items, as compared in layout.html.
const (
	menuTables        = "tables"
	menuColumns       = "columns"
	menuConstraints   = "constraints"
	menuRelationships = "relationships"
)

// tablesPage is the top page (index.html): a summary of the database and the
// list of tables.
type tablesPage struct {
	page
	Desc   string
	Tables []tableRow
}

type tableRow struct {
	Name    string
	Href    string
	Type    string
	View    bool
	Columns int
	Comment string
}

type tablePage struct {
	page
	Table       *schema.Table
	Columns     []columnRow
	ShowExtra   bool
	Constraints []*schema.Constraint
	Parents     relationTable
	Children    relationTable
	// The comment columns are shown only when some item has a comment: few
	// databases comment their indexes, constraints and triggers.
	IndexComments      bool
	ConstraintComments bool
	TriggerComments    bool
	// Diagram is inline SVG generated by Graphviz from escaped input, so it is trusted.
	Diagram template.HTML
}

type columnRow struct {
	*schema.Column
	Keys []keyBadge
}

// keyBadge is a PK or FK mark of a column. A column has one FK badge per
// relation it belongs to (it can be in several, some of them composite), each
// linking to that relation's parent table.
type keyBadge struct {
	Label   string
	Href    string
	Title   string
	Virtual bool
}

type columnsPage struct {
	page
	Columns   []tableColumnRow
	ShowExtra bool
}

// tableColumnRow is a column with its table, for lists across tables.
type tableColumnRow struct {
	Table     string
	TableHref string
	columnRow
}

// constraintsPage lists the constraints defined in the database. Virtual
// relations are not constraints and are on the relationships page.
type constraintsPage struct {
	page
	Constraints []tableConstraintRow
	ShowComment bool
}

type tableConstraintRow struct {
	Table     string
	TableHref string
	*schema.Constraint
}

// relationshipsPage shows the relations between tables, from foreign keys
// and virtual relations, as diagrams and as a list.
type relationshipsPage struct {
	page
	// Keys and All are the key-columns-only and all-columns variants of the
	// whole-schema diagram; inline SVG generated by Graphviz from escaped input.
	Keys      template.HTML
	All       template.HTML
	Relations relationTable
}

// relationTable is a list of relations. On a table page one end is the table
// itself, so only the other end is shown.
type relationTable struct {
	Rows       []relationRow
	ShowChild  bool
	ShowParent bool
}

// relationRow is a relation from the child table to the parent table.
type relationRow struct {
	Child       string
	ChildHref   string
	Parent      string
	ParentHref  string
	Columns     string
	Cardinality string
	Virtual     bool
	Def         string
}

func (site *Site) newTablesPage() tablesPage {
	s := site.schema
	p := tablesPage{
		page: page{Title: "Tables - " + dbTitle(s), DBName: dbTitle(s), Current: menuTables},
		Desc: s.Desc,
	}
	tables, views := 0, 0
	for _, t := range s.Tables {
		if t.View {
			views++
		} else {
			tables++
		}
		p.Tables = append(p.Tables, tableRow{
			Name:    t.Name,
			Href:    site.tableHref(p.Root, t),
			Type:    t.Type,
			View:    t.View,
			Columns: len(t.Columns),
			Comment: t.Comment,
		})
	}
	p.Count = plural(tables, "table", "tables")
	if views > 0 {
		p.Count += ", " + plural(views, "view", "views")
	}
	return p
}

func (site *Site) newTablePage(t *schema.Table) tablePage {
	s := site.schema
	p := tablePage{
		page:        page{Root: "../", Title: t.Name + " - " + dbTitle(s), DBName: dbTitle(s)},
		Table:       t,
		Constraints: t.Constraints,
	}
	parents := site.relations.Parents(t)
	p.Columns, p.ShowExtra = site.columnRows(p.Root, t, parents)
	p.Parents = relationTable{ShowParent: true}
	for _, r := range parents {
		p.Parents.Rows = append(p.Parents.Rows, site.relationRow(p.Root, r))
	}
	p.Children = relationTable{ShowChild: true}
	for _, r := range site.relations.Children(t) {
		p.Children.Rows = append(p.Children.Rows, site.relationRow(p.Root, r))
	}
	p.IndexComments = anyComment(t.Indexes, func(x *schema.Index) string { return x.Comment })
	p.ConstraintComments = anyComment(t.Constraints, func(x *schema.Constraint) string { return x.Comment })
	p.TriggerComments = anyComment(t.Triggers, func(x *schema.Trigger) string { return x.Comment })
	//nolint:gosec // SVG generated by Graphviz; all input text is escaped in the DOT source.
	p.Diagram = template.HTML(site.tableDiagrams[t])
	return p
}

// columnRows returns the column rows of t with their key badges, and whether
// any column has an extra definition (e.g. auto_increment) to show. parents
// are the relations in which t is the child.
func (site *Site) columnRows(root string, t *schema.Table, parents []*schema.Relation) (rows []columnRow, showExtra bool) {
	pk := make(map[string]bool)
	for _, c := range t.Constraints {
		if c.Kind == schema.ConstraintPrimaryKey {
			for _, col := range c.Columns {
				pk[col] = true
			}
		}
	}
	for _, c := range t.Columns {
		row := columnRow{Column: c}
		if pk[c.Name] {
			row.Keys = append(row.Keys, keyBadge{Label: "PK", Title: "Primary key"})
		}
		// FK marks come from relations rather than FK constraints so that
		// virtual relations are shown too.
		for _, r := range parents {
			if contains(r.Columns, c.Name) {
				row.Keys = append(row.Keys, site.fkBadge(root, r))
			}
		}
		if c.ExtraDef != "" {
			showExtra = true
		}
		rows = append(rows, row)
	}
	return rows, showExtra
}

func (site *Site) newColumnsPage() columnsPage {
	s := site.schema
	p := columnsPage{page: page{Title: "Columns - " + dbTitle(s), DBName: dbTitle(s), Current: menuColumns}}
	for _, t := range s.Tables {
		rows, extra := site.columnRows(p.Root, t, site.relations.Parents(t))
		p.ShowExtra = p.ShowExtra || extra
		for _, r := range rows {
			p.Columns = append(p.Columns, tableColumnRow{Table: t.Name, TableHref: site.tableHref(p.Root, t), columnRow: r})
		}
	}
	p.Count = plural(len(p.Columns), "column", "columns")
	return p
}

func (site *Site) newConstraintsPage() constraintsPage {
	s := site.schema
	p := constraintsPage{page: page{Title: "Constraints - " + dbTitle(s), DBName: dbTitle(s), Current: menuConstraints}}
	for _, t := range s.Tables {
		for _, c := range t.Constraints {
			p.Constraints = append(p.Constraints, tableConstraintRow{Table: t.Name, TableHref: site.tableHref(p.Root, t), Constraint: c})
			p.ShowComment = p.ShowComment || c.Comment != ""
		}
	}
	p.Count = plural(len(p.Constraints), "constraint", "constraints")
	return p
}

func (site *Site) newRelationshipsPage() relationshipsPage {
	s := site.schema
	p := relationshipsPage{
		page: page{Title: "Relationships - " + dbTitle(s), DBName: dbTitle(s), Fill: true, Current: menuRelationships},
		//nolint:gosec // SVG generated by Graphviz; all input text is escaped in the DOT source.
		Keys: template.HTML(site.wholeKeys),
		//nolint:gosec // SVG generated by Graphviz; all input text is escaped in the DOT source.
		All:       template.HTML(site.wholeAll),
		Relations: relationTable{ShowChild: true, ShowParent: true},
	}
	for _, r := range s.Relations {
		p.Relations.Rows = append(p.Relations.Rows, site.relationRow(p.Root, r))
	}
	p.Count = plural(len(s.Relations), "relationship", "relationships")
	return p
}

// anyComment reports whether some item has a comment.
func anyComment[T any](items []T, comment func(T) string) bool {
	for _, x := range items {
		if comment(x) != "" {
			return true
		}
	}
	return false
}

// plural formats a count with the singular or plural noun.
func plural(n int, singular, pluralForm string) string {
	if n == 1 {
		return "1 " + singular
	}
	return fmt.Sprintf("%d %s", n, pluralForm)
}

func (site *Site) tableHref(root string, t *schema.Table) string {
	return root + tablesDir + "/" + site.files[t]
}

func (site *Site) fkBadge(root string, r *schema.Relation) keyBadge {
	title := "References " + r.ParentTable.Name + " " + columnList(r.ParentColumns)
	if r.Virtual {
		title = "Virtual relation: " + title
	}
	return keyBadge{
		Label:   "FK",
		Href:    site.tableHref(root, r.ParentTable),
		Title:   title,
		Virtual: r.Virtual,
	}
}

func (site *Site) relationRow(root string, r *schema.Relation) relationRow {
	return relationRow{
		Child:       r.Table.Name,
		ChildHref:   site.tableHref(root, r.Table),
		Parent:      r.ParentTable.Name,
		ParentHref:  site.tableHref(root, r.ParentTable),
		Columns:     columnList(r.Columns) + " → " + columnList(r.ParentColumns),
		Cardinality: cardinalityPair(r),
		Virtual:     r.Virtual,
		Def:         r.Def,
	}
}

// columnList formats relation columns; composite ones are parenthesized so
// that "(a, b) → (x, y)" reads as a pairwise mapping.
func columnList(cols []string) string {
	if len(cols) == 1 {
		return cols[0]
	}
	return "(" + strings.Join(cols, ", ") + ")"
}

// cardinalityPair formats "child : parent", e.g. "0..* : 1" for many children per parent.
func cardinalityPair(r *schema.Relation) string {
	child, parent := cardinality(r.Cardinality), cardinality(r.ParentCardinality)
	if child == "" && parent == "" {
		return ""
	}
	return orUnknown(child) + " : " + orUnknown(parent)
}

func cardinality(c schema.Cardinality) string {
	switch c {
	case "zero_or_one":
		return "0..1"
	case "exactly_one":
		return "1"
	case "zero_or_more":
		return "0..*"
	case "one_or_more":
		return "1..*"
	default:
		return string(c)
	}
}

func orUnknown(s string) string {
	if s == "" {
		return "?"
	}
	return s
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

func dbTitle(s *schema.Schema) string {
	if s.Name != "" {
		return s.Name
	}
	return "Database"
}
