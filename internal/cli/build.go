package cli

import (
	"fmt"
	"path/filepath"

	"github.com/spf13/cobra"

	"github.com/onozaty/dbfolio/internal/input/tbls"
	"github.com/onozaty/dbfolio/internal/output"
	"github.com/onozaty/dbfolio/internal/render"
)

// DefaultOutputDir is tool-specific so that a project's own docs/ is never overwritten by accident.
const DefaultOutputDir = "dbfolio-docs"

func newBuildCmd() *cobra.Command {
	var outDir string
	var force bool

	cmd := &cobra.Command{
		Use:   "build <schema.json>",
		Short: "Generate HTML documentation from a tbls schema.json",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runBuild(cmd, args[0], outDir, force)
		},
	}
	cmd.Flags().StringVarP(&outDir, "output", "o", DefaultOutputDir, "output directory")
	cmd.Flags().BoolVar(&force, "force", false, "write into a non-empty directory not generated by dbfolio (existing files are kept)")
	return cmd
}

func runBuild(cmd *cobra.Command, schemaPath, outDir string, force bool) error {
	// Load before touching the output directory so that a bad input never cleans previous output.
	s, err := tbls.Load(schemaPath)
	if err != nil {
		return err
	}

	if err := output.Prepare(outDir, force); err != nil {
		return err
	}

	if err := writeIndex(filepath.Join(outDir, "index.html"), s); err != nil {
		return err
	}

	_, err = fmt.Fprintf(cmd.OutOrStdout(), "Generated documentation for %d tables in %s\n", len(s.Tables), outDir)
	return err
}

func writeIndex(path string, s *tbls.Schema) (err error) {
	f, err := output.CreateFile(path)
	if err != nil {
		return err
	}
	defer func() {
		if cerr := f.Close(); cerr != nil && err == nil {
			err = fmt.Errorf("close %s: %w", path, cerr)
		}
	}()

	if err := render.Index(f, s); err != nil {
		return fmt.Errorf("render %s: %w", path, err)
	}
	return nil
}
